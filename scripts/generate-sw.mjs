import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

// Run after next build: include every exported asset, even lazy chunks and fonts.
async function walk(dir, prefix = "") {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(entries.map(async (entry) => {
    const path = `${prefix}/${entry.name}`;
    return entry.isDirectory() ? walk(join(dir, entry.name), path) : [path];
  }));
  return files.flat();
}
const assets = (await walk("out")).filter((path) => path !== "/sw.js").sort();
if (!assets.includes("/index.html")) throw new Error("Missing exported app shell");
const hash = createHash("sha256");
for (const asset of assets) {
  hash.update(asset);
  hash.update(await readFile(join("out", asset)));
}
const cacheName = `dater-shell-${hash.digest("hex").slice(0, 16)}`;
const worker = `/* Generated by scripts/generate-sw.mjs. Do not edit. */
const CACHE = ${JSON.stringify(cacheName)};
const ASSETS = ${JSON.stringify(assets)};

self.addEventListener("install", (event) => {
  // Installation is atomic: a failed asset leaves the previous worker in place.
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(
    ASSETS.map((url) => new Request(url, { cache: "reload" }))
  )));
  // No skipWaiting: keep existing tabs and their matching chunks together.
});
self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    for (const name of await caches.keys()) {
      if (name.startsWith("dater-shell-") && name !== CACHE) await caches.delete(name);
    }
    await self.clients.claim();
  })());
});
self.addEventListener("fetch", (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== "GET" || url.origin !== self.location.origin) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    // Start URLs with query strings still load the same local-only app shell.
    const key = request.mode === "navigate" && (url.pathname === "/" || url.pathname === "/index.html")
      ? "/index.html" : url.pathname;
    const cached = await cache.match(key);
    return cached || fetch(request);
  })());
});
`;
await writeFile("out/sw.js", worker);
console.log(`Precached ${assets.length} files in ${cacheName}`);
